def _audit_recon():
    """把 CSV 逐期加总，与 `_REF` 的查核／核阅数对账。拿不到返回 None。

    分两组报：**合计**一组、**分部**一组。分开报是必要的 —— 合计七期全部逐位相等，
    而分部有一期差 1 千元（官方自己在季度拆分上的进位差）。
    合成一个数会把「合计完全对得上」这条最强的证据稀释掉。
    """
    rs = _rows()
    if not rs:
        return None
    by = {}
    for r in rs:
        t = _fv(r.get(_COL))
        k = _fv(r.get(_TURNKEY))
        n = _fv(r.get(_NRE_COL))
        if t is None:
            continue
        by[r['month']] = (t * 1000.0, None if k is None else k * 1000.0,
                          None if n is None else n * 1000.0)
    tot = {'n': 0, 'exact': 0, 'maxabs': 0.0, 'worst': None}
    seg = {'n': 0, 'exact': 0, 'maxabs': 0.0, 'worst': None}
    for lab, m0, m1, rtot, rtk, rnre, _src in _REF:
        ms = [m for m in by if m0 <= m <= m1]
        want = (int(m1[:4]) - int(m0[:4])) * 12 + int(m1[5:7]) - int(m0[5:7]) + 1
        if len(ms) != want:                     # 期间没配齐就整条跳过，不报半个结论
            continue
        s_t = sum(by[m][0] for m in ms)
        for box, mine, ref in ((tot, s_t, rtot),
                               (seg, sum(by[m][1] for m in ms) if all(
                                   by[m][1] is not None for m in ms) else None, rtk),
                               (seg, sum(by[m][2] for m in ms) if all(
                                   by[m][2] is not None for m in ms) else None, rnre)):
            if mine is None or ref is None:     # 该期没有这一栏的审计参照数 ⇒ 不报
                continue
            d = abs(mine - ref)
            box['n'] += 1
            if d < 0.5:
                box['exact'] += 1
            elif d > box['maxabs']:
                box['maxabs'], box['worst'] = d, lab
    if not tot['n']:
        return None
    return {'tot': tot, 'seg': seg, 'periods': tot['n']}


def _seg_additivity():
    """逐月「Turnkey + NRE&Others 是否恰好等于合计」。拿不到返回 None。

    页面在 brief 第 4 句和页尾都会说「合并 ≡ 各分部之和」。那是一句**恒等式断言**，
    所以它必须在构建期被这份 CSV 自己验一遍，而不是引用一句读来的话。
    """
    rs = _rows()
    if not rs:
        return None
    n, worst, wm = 0, 0.0, None
    for r in rs:
        t = _fv(r.get(_COL))
        k = _fv(r.get(_TURNKEY))
        v = _fv(r.get(_NRE_COL))
        if None in (t, k, v):
            continue
        n += 1
        d = abs((k + v) - t) * 1000.0            # NT$K
        if d > worst:
            worst, wm = d, r['month']
    return {'n': n, 'worst_ntdk': worst, 'worst_month': wm} if n else None


def _span():
    """(首月, 末月, 月数)。拿不到返回 (None, None, 0)。"""
    rs = _rows() or []
    ms = [r['month'] for r in rs if _fv(r.get(_COL)) is not None]
    return (ms[0], ms[-1], len(ms)) if ms else (None, None, 0)


def _seg_span():
    """两条分部列**都有值**的 (首月, 月数)；拿不到返回 (None, 0)。

    为什么必须现算：本页有两个起点（合并列 2016-01、分部列 2017-01，见文件头 G），
    两者相差几个月会随每月新增而变、也会随哪天 IR 补上更早的拆分而变。
    页上凡是说「分部那一列覆盖的是 N 个月 / 自 X 起」的地方一律查这里 ——
    写死的那一刻就注定了下个月是假的（本文件的「115 个月」栽过一次，本轮拔掉）。
    """
    ms = [r['month'] for r in (_rows() or [])
          if _fv(r.get(_TURNKEY)) is not None and _fv(r.get(_NRE_COL)) is not None]
    return (ms[0], len(ms)) if ms else (None, 0)


def _remark_seg():
    """核对表那一列的 MOPS 备注原文里，公司自己怎么点分部的名。拿不到返回 None。

    为什么本页要算这个：堆叠柱把 `NRE & Others` 画成**一整块**，视觉上暗示它是一项
    单一业务。反证不必外求 —— 就在同一页的核对表里：公司在备注栏里把「晶圓產品」
    与「委託設計(NRE)」当两件事分开说，而「其他」一次都没被点过名。
    这是**页内可逐格复核**的证据（读者对着那一列数得出来），所以它比任何转录的
    断言都硬；也因此它必须现算 —— 备注逐月在变，写死的计数下个月就是假的。

    只统计核对表**实际印出来的**那 `_CHECK_ROWS` 个月，不是全表 24 行：
    图注说「上面那一列」，指的就得是上面那一列。
    `series/mops_remarks.csv` 是别人维护的文件，读不到/列变了一律返回 None，
    那一句话整句消失，不带半个数上页。
    """
    ms = [r['month'] for r in (_rows() or []) if _fv(r.get(_COL)) is not None]
    if not ms:
        return None
    want = set(ms[-_CHECK_ROWS:])
    try:
        with open(os.path.join(_facts.SERIES, 'mops_remarks.csv'),
                  encoding='utf-8') as fh:
            rk = [r for r in csv.DictReader(fh)
                  if r.get('ticker') == 'guc' and r.get('month') in want]
    except Exception:
        return None
    if not rk:
        return None
    txt = [(r.get('remark') or '').strip() for r in rk]
    filled = [t for t in txt if t]
    if not filled:
        return None
    return {'shown': len(want), 'rows': len(rk), 'filled': len(filled),
            # 繁体原文里的写法：委託設計 / NRE 指同一件事，其他 = Others。
            'nre': sum(1 for t in filled if '委託設計' in t or 'NRE' in t),
            'others': sum(1 for t in filled if '其他' in t or 'Others' in t),
            'variants': len(set(filled))}


