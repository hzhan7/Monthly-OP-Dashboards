    ys = [(m, x) for m, x in ys if x is not None]
    if not ys or not _S:
        return None
    lo_m, lo_v = min(_S.items(), key=lambda kv: kv[1])
    hi_m, hi_v = max(_S.items(), key=lambda kv: kv[1])
    return {'lo_m': lo_m, 'lo': lo_v, 'hi_m': hi_m, 'hi': hi_v,
            'ratio': (hi_v / lo_v) if lo_v else None,
            'ylo': min(ys, key=lambda t: t[1]), 'yhi': max(ys, key=lambda t: t[1]),
            'n': len(ys)}


