def _series():
    try:
        with open(os.path.join(_facts.SERIES, _CSV), encoding='utf-8') as fh:
            rows = list(csv.DictReader(fh))
    except OSError:
        return {}
    out = {}
    for r in rows:
        try:
            out[r['month']] = float((r[_COL] or '').strip())
        except (KeyError, TypeError, ValueError):
            continue
    return out


_S = _series()
_M = sorted(_S)


def _k(m):
    """某月的申报原值，单位千元（CSV 存的是 NT$mn，小数点后三位就是千元位）。"""
    return round(_S[m] * 1000.0)


def _zh(ym):
    return f'{ym[:4]} 年 {int(ym[5:7])} 月'


def _pct(xs, p):
    ss = sorted(xs)
    if not ss:
        return None
    k = (len(ss) - 1) * p
    lo, hi = int(k), min(int(k) + 1, len(ss) - 1)
    return ss[lo] + (ss[hi] - ss[lo]) * (k - lo)


def _yoy_at(m):
    p = f'{int(m[:4]) - 1}-{m[5:7]}'
    if p in _S and _S[p]:
        return (_S[m] / _S[p] - 1.0) * 100.0
    return None


def _annual_recon():
    """[(年, 月度加总千元, 审计千元, diff千元, 相对%)]，只取 12 个月齐全且有审计数的年。"""
    by = {}
    for m in _M:
        by.setdefault(int(m[:4]), []).append(m)
    out = []
    for y in sorted(by):
        if len(by[y]) != 12 or y not in _AUDITED_K:
            continue
        s = sum(_k(m) for m in by[y])
        a = _AUDITED_K[y]
        out.append((y, s, a, s - a, (s - a) / a * 100.0))
    return out


def _interim_recon():
    """[(标签, 月度加总千元, 官方累计千元, diff千元)]，月份不齐的那条直接不出。"""
    out = []
    for lab, (year, upto, official) in sorted(_OFFICIAL_CUM_K.items()):
        got = [m for m in _M if int(m[:4]) == year and int(m[5:7]) <= upto]
        if len(got) != upto:
            continue
        s = sum(_k(m) for m in got)
        out.append((lab, s, official, s - official))
    return out


def _basis_gap_2013():
    """2013 月度加总（旧口径）vs FY2014 报表里重述后的 2013 比较数。"""
    ms = [m for m in _M if m.startswith('2013')]
    if len(ms) != 12:
        return None
    s = sum(_k(m) for m in ms)
    return {'sum': s, 'restated': _RESTATED_2013_K, 'old': _AUDITED_K.get(2013),
            'diff': s - _RESTATED_2013_K,
            'pct': (s / _RESTATED_2013_K - 1.0) * 100.0}


def _q1_checks():
    """两条季度算术：2014Q1（同口径）与 2013Q1（不同口径）。"""
    q14 = [f'2014-{i:02d}' for i in (1, 2, 3)]
    q13 = [f'2013-{i:02d}' for i in (1, 2, 3)]
    if any(m not in _S for m in q14 + q13):
        return None
    s14, s13 = sum(_k(m) for m in q14), sum(_k(m) for m in q13)
    return {'s14': s14, 'o14': _Q1_2014_K, 'd14': s14 - _Q1_2014_K,
            's13': s13, 'o13': _Q1_2013_COMP_K,
            'd13': s13 - _Q1_2013_COMP_K,
            'p13': (s13 / _Q1_2013_COMP_K - 1.0) * 100.0}


def _restated_yoy_rows():
    """2014-09~12：本序列现算同比 vs 用公司重述基期算出的同比。两边都现算。"""
    out = []
    for base_m, base_k in sorted(_RESTATED_BASE_2013_K.items()):
        cur_m = f'{int(base_m[:4]) + 1}-{base_m[5:7]}'
        if cur_m not in _S or base_m not in _S or not _S[base_m] or not base_k:
            continue
        mine = _yoy_at(cur_m)
        theirs = (_k(cur_m) / base_k - 1.0) * 100.0
        if mine is None:
            continue
        out.append({'m': cur_m, 'mine': mine, 'theirs': theirs,
                    'base_old': _k(base_m), 'base_new': base_k,
                    'base_pct': (base_k / _k(base_m) - 1.0) * 100.0})
    return out


