_EXPLAINS_ZH = {'mom': '环比', 'yoy': '同比', 'both': '环比与同比'}


def _presser_brief(ctx):
    """当月新闻稿有增减原因说明就写一句，没有就返回空串（退回底座替补句）。

    整段套在 try 里：为一句注脚把整页构建带走不值当（与本文件其余现算同一条规矩）。
    `explains` 没登记（`-`）时也返回空串 —— 说不清它解释的是哪个数，这句话就没有价值，
    而「它解释的是哪个数」恰恰是本页加这一句的**全部理由**。
    """
    try:
        cur = str(ctx['ds'].all[ctx['i']])
        pr = _pr_at(cur)
        if not pr:
            return ''
        what = _EXPLAINS_ZH.get(pr['explains'])
        if not what:
            return ''
        how = f'分 {pr["n"]} 点说明增减原因' if pr['n'] else '括注了一句增减原因'
        rare = (f'（英文版 {_PR_SCAN["n"]} 篇里第一次）' if _pr_is_first(cur) else '')
        # 「不是同比」只在公司自己只说了环比时才写 —— 它说了同比就没有这个歧义。
        vs = '、不是同比' if pr['explains'] == 'mom' else ''
        return (f'公司当月新闻稿{how}{rare}：解释的是这个{what}{vs}；全文见页尾。')
    except Exception:                      # noqa: BLE001 —— 见上面那段
        return ''


