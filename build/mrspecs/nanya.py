def _release_days():
    """新闻稿发布日在当月的第几天：{n, lo, hi, med}。拿不到返回 None。

    这一列在 `series/nanya.csv` 里**没有**（那张表只有 month + 金额两列），
    在 `series/nanya_notes.csv` 里**有**（`release_date`）—— 所以这句话能现算的
    范围就是那张表覆盖的那几个月，页面必须把这个范围写出来。
    """
    ds = []
    for m, r in sorted(_NOTES.items()):
        d = (r.get('release_date') or '').strip()
        if len(d) == 10 and d[:7] >= m:      # 次月发布，日期必须不早于当月
            try:
                ds.append(int(d[8:10]))
            except ValueError:
                continue
    if len(ds) < 6:
        return None
    ss = sorted(ds)
    n = len(ss)
    med = ss[n // 2] if n % 2 else (ss[n // 2 - 1] + ss[n // 2]) / 2
    return {'n': n, 'lo': ss[0], 'hi': ss[-1], 'med': med,
            'from': min(_NOTES), 'to': max(_NOTES)}


